// contractgen keeps the frontend's small set of shared API response types in
// sync with the Go structs that the handlers actually serialize.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"strings"
)

type contract struct {
	file string
	name string
}

var contracts = []contract{
	{"internal/httpapi/auth.go", "SessionResponse"},
	{"internal/httpapi/auth.go", "LoginResponse"},
	{"internal/httpapi/auth.go", "LogoutResponse"},
	{"internal/subscribers/types.go", "Subscriber"},
}

const output = "web/src/lib/generated-contracts.ts"

func main() {
	check := flag.Bool("check", false, "fail if generated contracts differ")
	flag.Parse()
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./cmd/contractgen; DO NOT EDIT.\n\n")
	for _, c := range contracts {
		if err := appendType(&b, c); err != nil {
			fatal(err)
		}
	}
	want := bytes.TrimSuffix(b.Bytes(), []byte("\n"))
	if *check {
		got, err := os.ReadFile(output)
		if err != nil || !bytes.Equal(got, want) {
			fatal(fmt.Errorf("%s is stale; run go run ./cmd/contractgen", output))
		}
		return
	}
	if err := os.MkdirAll(filepath.Dir(output), 0755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(output, want, 0644); err != nil {
		fatal(err)
	}
}

func appendType(b *bytes.Buffer, c contract) error {
	f, err := parser.ParseFile(token.NewFileSet(), c.file, nil, 0)
	if err != nil {
		return err
	}
	for _, decl := range f.Decls {
		g, ok := decl.(*ast.GenDecl)
		if !ok || g.Tok != token.TYPE {
			continue
		}
		for _, spec := range g.Specs {
			t, ok := spec.(*ast.TypeSpec)
			if !ok || t.Name.Name != c.name {
				continue
			}
			s, ok := t.Type.(*ast.StructType)
			if !ok {
				return fmt.Errorf("%s must be a struct", c.name)
			}
			fmt.Fprintf(b, "export interface %s {\n", c.name)
			for _, field := range s.Fields.List {
				if field.Tag == nil {
					return fmt.Errorf("%s has an untagged field", c.name)
				}
				tag := reflect.StructTag(strings.Trim(field.Tag.Value, "`"))
				parts := strings.Split(tag.Get("json"), ",")
				if parts[0] == "-" {
					continue
				}
				if len(field.Names) != 1 || parts[0] == "" {
					return fmt.Errorf("%s has unsupported JSON field", c.name)
				}
				typ, err := tsType(field.Type)
				if err != nil {
					return fmt.Errorf("%s.%s: %w", c.name, field.Names[0].Name, err)
				}
				optional := ""
				if len(parts) > 1 && slicesContains(parts[1:], "omitempty") {
					optional = "?"
					if strings.HasSuffix(typ, " | null") {
						typ = strings.TrimSuffix(typ, " | null")
					}
				}
				fmt.Fprintf(b, "  %s%s: %s;\n", parts[0], optional, typ)
			}
			b.WriteString("}\n\n")
			return nil
		}
	}
	return fmt.Errorf("%s missing in %s", c.name, c.file)
}

func tsType(expr ast.Expr) (string, error) {
	switch x := expr.(type) {
	case *ast.Ident:
		switch x.Name {
		case "string":
			return "string", nil
		case "bool":
			return "boolean", nil
		case "int", "int64", "int32", "float64", "float32", "uint", "uint64":
			return "number", nil
		case "any":
			return "unknown", nil
		default:
			return "", fmt.Errorf("unsupported type %s", x.Name)
		}
	case *ast.StarExpr:
		t, err := tsType(x.X)
		return t + " | null", err
	case *ast.ArrayType:
		t, err := tsType(x.Elt)
		return "Array<" + t + ">", err
	case *ast.MapType:
		key, ok := x.Key.(*ast.Ident)
		if !ok || (key.Name != "string" && key.Name != "int64" && key.Name != "int") {
			return "", fmt.Errorf("unsupported map key")
		}
		t, err := tsType(x.Value)
		return "Record<string, " + t + ">", err
	default:
		return "", fmt.Errorf("unsupported field type %T", expr)
	}
}

func slicesContains(xs []string, want string) bool {
	for _, x := range xs {
		if x == want {
			return true
		}
	}
	return false
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
